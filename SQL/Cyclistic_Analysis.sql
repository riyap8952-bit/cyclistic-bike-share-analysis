  COUNT(*) AS total_rides
FROM `speedy-victory-507504-c5.CASE_STUDY_CYCLISTIC.12_months_combined_cleaned`
WHERE started_at >= TIMESTAMP('2025-10-01 00:00:00+00')
  AND started_at < TIMESTAMP('2026-10-01 00:00:00+00');

