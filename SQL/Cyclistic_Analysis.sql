## QUERY TO FIND DUPLICATE VALUES ACROSS COMBINED DATA TABLE

 SELECT * 
FROM `speedy-victory-507504-c5.CASE_STUDY_CYCLISTIC.12_months_combined` 
WHERE ride_id IN (
    SELECT ride_id
    FROM `speedy-victory-507504-c5.CASE_STUDY_CYCLISTIC.12_months_combined` 
    GROUP BY ride_id
    HAVING COUNT (*) > 1 )
    ORDER BY ride_id 

